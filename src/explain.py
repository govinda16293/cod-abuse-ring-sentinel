class Attributor:
    """TreeSHAP over the uncalibrated booster.

    Attribution is taken on the booster's margin, not on the calibrated
    probability: isotonic regression is a monotone post-hoc map, so it changes
    the number but not the ordering or the reasons. Attributing through it would
    add a step with no interpretable per-feature meaning.
    """

    def __init__(self, bundle):
        import shap
        self.clf = bundle["booster"]
        self.features = bundle["features"]
        self.explainer = shap.TreeExplainer(self.clf.booster_)

    def shap_values(self, X):
        sv = self.explainer.shap_values(X)
        if isinstance(sv, list):
            sv = sv[1] if len(sv) > 1 else sv[0]
        sv = np.asarray(sv)
        if sv.ndim == 3:
            sv = sv[:, :, 1] if sv.shape[2] > 1 else sv[:, :, 0]
        return sv

    def top_evidence(self, x_row, sv_row, k=5, direction="up"):
        idx = np.argsort(-sv_row if direction == "up" else sv_row)[:k]
        out = []
        for j in idx:
            name = self.features[j]
            contrib = float(sv_row[j])
            if direction == "up" and contrib <= 0:
                continue
            if direction == "down" and contrib >= 0:
                continue
            val = float(x_row[j])
            fn = EVIDENCE.get(name)
            out.append(dict(feature=name, value=val, contribution=contrib,
                            sentence=fn(val) if fn else "%s = %.3f" % (name, val)))
        return out


def caveats(order_facts, feat_map):
    """What this flag does NOT establish. Written from the same feature row.

    The brief asks for an honest list of what the system could not resolve. This
    is that list, per order, and it is generated from rules over the features
    rather than by asking the model to be humble.
    """
    out = []
    g = feat_map.get
    if g("cust_prior_orders", 0) == 0:
        out.append("This account has no order history, so every behavioural signal is absent; "
                   "the score rests entirely on network structure.")
    if g("addr_distinct_customers", 0) >= 1 and g("comp_max_tenure_days", 0) > 365:
        out.append("At least one account in this cluster is over a year old. Order data alone "
                   "cannot separate a co-ordinated group from a genuine shared household.")
    if g("addr_is_new_variant_of_known_cluster", 0) >= 0.5:
        out.append("The address matched an existing cluster by text normalisation, not by "
                   "geocoding. A normalisation error would produce this same signal.")
    if g("comp_size", 1) <= 1:
        out.append("No identity links were found at all; this flag is behavioural only and is "
                   "the weakest kind of evidence this system produces.")
    if g("phone_neighbours_active", 0) > 0:
        out.append("Numerically adjacent phone numbers can also arise from a family or a small "
                   "business buying a connection block legitimately.")
    if not out:
        out.append("No specific counter-hypothesis was detected, which is not the same as none "
                   "existing.")
    return out


SYSTEM_PROMPT = """You are a risk-operations assistant for an e-commerce merchant's \
returns-abuse review queue. You write short justifications that a human reviewer reads \
before deciding whether to require prepayment on a cash-on-delivery order.

Hard rules:
- You are NOT the classifier. A calibrated model has already scored this order. Never \
agree or disagree with the score, never restate it as your own judgement, and never \
suggest a different score.
- Use ONLY the evidence supplied. Never introduce a fact that is not in the payload. \
Never speculate about the customer's identity, intent, motive or character.
- Write for the merchant's defensive side only. Never describe how detection could be \
avoided.
- Include the supplied caveats faithfully. They are the point, not a disclaimer.

Output 3 to 4 sentences of plain prose. First what the evidence shows, then what it does \
not establish. No bullet points, no headings, no preamble."""


def _dedupe(seq):
    """Several features can render to the same sentence (a one-member cluster has
    the same age as its only account). Say it once."""
    seen, out = set(), []
    for x in seq:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def _template_explanation(payload):
    sents = _dedupe([e["sentence"] for e in payload["evidence"]])
    ev = "; ".join(sents)
    top = sents[0] if sents else "no positive evidence"
    return ("Flagged for review at a calibrated abuse probability of %.3f. The strongest "
            "single factor is that %s. Supporting signals: %s. What this does not establish: %s"
            % (payload["probability"], top, ev, " ".join(payload["caveats"])))


def write_explanation(payload, use_llm=True, client=None):
    """Render one explanation. Falls back to a deterministic template with no key."""
    if not use_llm or not os.environ.get("ANTHROPIC_API_KEY"):
        return _template_explanation(payload), "template"
    try:
        if client is None:
            import anthropic
            client = anthropic.Anthropic()
        msg = client.messages.create(
            model=MODEL_ID, max_tokens=400, system=SYSTEM_PROMPT,
            messages=[{"role": "user",
                       "content": "Evidence payload (JSON):\n" + json.dumps(payload, indent=2)}])
        return msg.content[0].text.strip(), MODEL_ID
    except Exception as e:  # network, auth, rate limit - never break the pipeline
        return _template_explanation(payload), "template (LLM unavailable: %s)" % type(e).__name__


def build_payload(order_facts, x_row, sv_row, attributor, probability, band, k=5):
    feat_map = {attributor.features[j]: float(x_row[j]) for j in range(len(x_row))}
    up = attributor.top_evidence(x_row, sv_row, k=k, direction="up")
    down = attributor.top_evidence(x_row, sv_row, k=2, direction="down")
    return dict(
        order=order_facts,
        probability=float(probability),
        decision_band=band,
        evidence=up,
        counter_evidence=down,
        caveats=caveats(order_facts, feat_map),
    )
