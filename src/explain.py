"""Phase 5 - per-prediction attribution and the LLM explanation layer.

The boundary, stated once and enforced in code:

    The classifier decides. The LLM writes.

The language model never sees the label, never sees the threshold, and its
output never re-enters the decision path. It is handed a frozen, structured
payload - the order's facts plus the top TreeSHAP contributions already
converted into evidence sentences - and asked to render that payload as prose a
human reviewer can act on. If the API key is absent, a deterministic template
writer produces the same content without the prose polish, so the repo runs on a
clean machine with no key and no network.

That ordering matters for a second reason: an explanation generated from the
attributions is auditable against them. An explanation generated by asking a
model "is this fraud?" would be a second, uncalibrated classifier wearing a
justification costume.
"""
